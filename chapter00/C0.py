# ## Get Started
#
# If a static view of the FMP notebooks is enough for you, the exported HTML versions can be
# used right away without any installation. If you want to execute the Python code cells,
# you have to download the notebooks (along with the data), create an environment, and start
# a Jupyter server.

# %% [markdown]
# ## Overview
#
# The collection of FMP notebooks is organized along the eight chapters of the textbook:
#
# | Chapter | Title | Topics |
# |---------|-------|--------|
# | B | Basics | Python, Jupyter, Anaconda, multimedia, visualization, audio, libfmp |
# | C0 | Overview | Overview of the notebooks (this file) |
# | C1 | Music Representations | Music notation, MIDI, audio signal, waveform, pitch, loudness, timbre |
# | C2 | Fourier Analysis of Signals | DFT, FFT, STFT, sinusoid, exponential, Fourier transform |
# | C3 | Music Synchronization | Chroma feature, dynamic programming, DTW, alignment |
# | C4 | Music Structure Analysis | Similarity matrix, repetition, thumbnail, novelty, evaluation |
# | C5 | Chord Recognition | Harmony, music theory, chords, scales, templates, HMM |
# | C6 | Tempo and Beat Tracking | Onset, novelty, tempo, tempogram, beat, periodicity |
# | C7 | Content-Based Audio Retrieval | Identification, fingerprint, audio matching, version identification |
# | C8 | Musically Informed Audio Decomposition | Harmonic/percussive separation, F0, NMF |

