# ## About
#
# The FMP notebooks are a collection of educational material for teaching and learning
# Fundamentals of Music Processing (FMP) with a particular focus on the audio domain.
# Covering well-established topics in Music Information Retrieval (MIR) as motivating
# application scenarios, the FMP notebooks provide detailed textbook-like explanations
# of central techniques and algorithms in combination with Python code examples that
# illustrate how to implement the theory.
