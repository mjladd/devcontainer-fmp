# # Chapter 1: Music Representations
#
# Musical information can be represented in many different ways. Chapter 1 of
# [Muller, FMP, Springer 2015] covers three widely used music representations:
# sheet music, symbolic, and audio representations. In particular, it discusses
# musical and acoustic properties of audio signals including aspects such as
# frequency, pitch, dynamics, and timbre.
#
