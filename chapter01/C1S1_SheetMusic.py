# # Sheet Music Representations
#
# Following Section 1.1 of [Muller, FMP, Springer 2015], we look in this notebook
# at sheet music representations by giving some representative examples.
#
# **Sheet music**, also referred to as **musical score**, provides a visual
# representation of what we commonly refer to as the piece of music. Sheet music
# describes a musical work using a formal language based on musical symbols and
# letters, which are depicted in a graphical-textual form.

# %% [markdown]
# ## Example: Beethoven's Fifth
#
# Symphony No. 5 in C minor by Ludwig van Beethoven is one of the most popular
# and best-known compositions in classical music. It begins with the famous
# "short-short-short-long" motif, commonly referred to as the "fate motif."
#
# The difference between a synthesized and a real performance of the fate motive
# illustrates the creative interpretation involved in performing from sheet music.

# %% [markdown]
# ## Full Score
#
# A full orchestral score is used by conductors to direct rehearsals and
# performances. The various staves of the system specify the music according
# to the different instruments lined up in a fixed order:
# - Woodwinds (flute, oboe, clarinet, bassoon)
# - Brass (French horn, trumpet) and percussion (timpani)
# - Strings (violin, viola, cello, double bass)

# %% [markdown]
# ## Music Notation
#
# Music notation refers to a system for graphically representing music through symbols.
#
# ### Key Elements:
# - **Staff**: Five horizontal lines and four spaces representing different pitches
# - **Clef**: Symbol indicating the position of one particular note on the staff
# - **Key signature**: Indicates the key by specifying flat or sharp notes
# - **Time signature**: Defines beats per measure
# - **Note values**: Whole, half, quarter notes, etc.
# - **Rests**: Symbols for intervals of silence
# - **Articulation marks**: Indicate how notes are to be played

# %% [markdown]
# ## Note Components
#
# Each note is represented by a symbol consisting of:
# - **Note head**: Indicates pitch by placement on staff
# - **Stem**: Vertical line attached to note head
# - **Flag/Beam**: Indicates note duration
#
# Note durations:
# - Whole note: Reference value
# - Half note: Half the length of a whole note
# - Quarter note: Quarter the length of a whole note
# - And so on...

# %% [markdown]
# ## Staff Systems
#
# A single vertical line drawn to the left of multiple staves creates a
# **staff system**, indicating that the music on all staves is to be played
# simultaneously. A bracket shows groupings of instruments that function as a unit.

